import { readFileSync, writeFileSync } from "node:fs";

const target = process.argv[2];

if (!target) {
  console.error("Usage: node scripts/normalize-orval-client.mjs <generated-client.ts>");
  process.exit(2);
}

const input = readFileSync(target, "utf8");
const output = input
  .replace(/Generated by orval v([0-9.]+) .*/u, "Generated by orval v$1")
  .split("\n")
  .map((line) => line.trimEnd())
  .join("\n")
  .replace(/\n*$/u, "\n");

writeFileSync(target, output, "utf8");
